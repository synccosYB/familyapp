export type WordingOverrides = Record<string, string>;
type Values = Record<string, unknown>;

const placeholders = (text: string) =>
  [...new Set([...text.matchAll(/\{([A-Za-z][A-Za-z0-9_]*)\}/g)].map(match => match[1]))].sort().join(',');
const required = Object.fromEntries(Object.entries(defaults).map(([key, text]) => [key, placeholders(text)]));
let overrides: WordingOverrides = {};

export function validWording(key: string, text: unknown): text is string {
  return Object.hasOwn(defaults, key) && typeof text === 'string' && text.trim().length > 0 &&
    text.length <= 2000 && !/[\u0000-\u0008\u000b\u000c\u000e-\u001f]/.test(text) &&
    placeholders(text) === required[key];
}

export function applyWording(next: WordingOverrides) {
  overrides = Object.fromEntries(Object.entries(next).filter(([key, text]) => validWording(key, text)));
}

export function word(key: string, values: Values = {}) {
  const text = Object.hasOwn(overrides, key) ? overrides[key] : defaults[key];
  if (text === undefined) throw new Error('Missing wording key '+key);
  return text.replace(/\{([A-Za-z][A-Za-z0-9_]*)\}/g, (_match, name: string) => String(values[name] ?? ''));
}

export function htmlWord(key: string, values?: Values) {
  return word(key, values).replace(/[&<>"']/g, char => ({'&':'&amp;', '<':'&lt;', '>':'&gt;', '"':'&quot;', "'":'&#39;'})[char]!);
}
